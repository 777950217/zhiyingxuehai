/* ─── 工具函数 ─── */
export function getModuleById(id: string): Module | undefined {
  return ALL_MODULES.find(m => m.id === id);
}

export function getLessonById(lessonId: string): { module: Module; lesson: Lesson } | undefined {
  for (const mod of ALL_MODULES) {
    const lesson = mod.lessons.find(l => l.id === lessonId);
    if (lesson) return { module: mod, lesson };
  }
  return undefined;
}

export function getAdjacentLessons(lessonId: string): { prev?: Lesson; next?: Lesson } {
  const allLessons = ALL_MODULES.flatMap(m => m.lessons);
  const idx = allLessons.findIndex(l => l.id === lessonId);
  // 如果找不到当前课时，返回空对象
  if (idx === -1) {
    return { prev: undefined, next: undefined };
  }
  return {
    prev: idx > 0 ? allLessons[idx - 1] : undefined,
    next: idx < allLessons.length - 1 ? allLessons[idx + 1] : undefined,
  };
}

export function loadProgress(userId?: string): Record<string, boolean> {
  if (typeof window === 'undefined') return {};
  try {
    const saved = localStorage.getItem(getProgressStorageKey(userId));
    return saved ? JSON.parse(saved) : {};
  } catch { return {}; }
}

export function saveProgress(progress: Record<string, boolean>, userId?: string) {
  try { localStorage.setItem(getProgressStorageKey(userId), JSON.stringify(progress)); } catch { /* ignore */ }
}

/**
 * Fetch learning progress from server (Supabase).
 * Merges with localStorage to ensure no data is lost.
 */
export async function loadProgressFromAPI(token: string, userId?: string): Promise<Record<string, boolean>> {
  try {
    const res = await fetch('/api/personal/learning-progress', {
      headers: { Authorization: `Bearer ${token}` },
    });
    if (!res.ok) return loadProgress(userId); // fallback to localStorage
    const { learnedIds } = await res.json() as { learnedIds: string[] };
    const local = loadProgress(userId);
    // Merge: server is source of truth, but keep any local-only entries
    const merged: Record<string, boolean> = { ...local };
    for (const id of learnedIds) {
      merged[id] = true;
    }
    saveProgress(merged, userId);
    return merged;
  } catch {
    return loadProgress(userId); // fallback to localStorage
  }
}

/**
 * Toggle a lesson's learned status and sync to both localStorage and API.
 */
export async function toggleLessonProgress(
  lessonId: string,
  learned: boolean,
  token?: string,
  userId?: string,
): Promise<void> {
  const progress = loadProgress(userId);
  if (learned) {
    progress[lessonId] = true;
  } else {
    delete progress[lessonId];
  }
  saveProgress(progress, userId);

  // Sync to API in background (non-blocking)
  if (token) {
    fetch('/api/personal/learning-progress', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
      body: JSON.stringify({ lessonId, learned }),
    }).catch(() => { /* silent fail — localStorage is the fallback */ });
  }
}

