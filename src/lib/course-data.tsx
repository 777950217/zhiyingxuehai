export function renderLines(text: string) {
  return text.split('\n').map((line, i) => {
    const trimmed = line.trim();
    if (!trimmed) return <div key={i} className="h-2" />;
    // Bold marker: **text**
    if (trimmed.startsWith('**') && trimmed.endsWith('**')) {
      return <p key={i} className="font-bold text-slate-800 mt-3 mb-1">{trimmed.slice(2, -2)}</p>;
    }
    // Sub-heading marker: ## text
    if (trimmed.startsWith('## ')) {
      return <h4 key={i} className="font-semibold text-slate-800 mt-4 mb-1 text-[15px]">{trimmed.slice(3)}</h4>;
    }
    // Bullet point
    if (trimmed.startsWith('- ')) {
      const content = trimmed.slice(2);
      const highlighted = content.replace(/「([^」]+)」/g, '「<span class="font-semibold text-blue-700">$1</span>」');
      return (
        <div key={i} className="flex items-start gap-2 ml-1 my-1">
          <span className="text-blue-400 mt-1.5 shrink-0">•</span>
          <span dangerouslySetInnerHTML={{ __html: highlighted }} />
        </div>
      );
    }
    // Quote marker: > text
    if (trimmed.startsWith('> ')) {
      return (
        <div key={i} className="border-l-3 border-blue-400 pl-3 py-1 my-2 bg-blue-50/50 rounded-r text-slate-700 text-sm">
          {trimmed.slice(2)}
        </div>
      );
    }
    // Case marker: 案例: / 案例：
    if (trimmed.startsWith('案例') || trimmed.startsWith('案例：') || trimmed.startsWith('案例:')) {
      return <p key={i} className="font-semibold text-amber-700 mt-3 mb-1">{trimmed}</p>;
    }
    // Default paragraph
    const highlighted = trimmed.replace(/「([^」]+)」/g, '「<span class="font-semibold text-blue-700">$1</span>」');
    return <p key={i} className="my-1 leading-relaxed" dangerouslySetInnerHTML={{ __html: highlighted }} />;
  });
}

