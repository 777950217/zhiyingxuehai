/* ─── 课程顺序锁定：获取所有课程的有序列表 ─── */
export function getOrderedLessons(): Lesson[] {
  return ALL_MODULES.flatMap(m => m.lessons);
}

/**
 * 检查某课是否解锁（前置课程是否已提交笔记）
 * 第1课默认解锁
 * 判断标准：前置课程的 localStorage(knowledge-notes-v2) 中有 userNote 且非空
 */
export function isLessonUnlocked(lessonNum: number): boolean {
  if (lessonNum <= 1) return true;
  const prevLesson = getOrderedLessons().find(l => l.num === lessonNum - 1);
  if (!prevLesson) return true;
  // 检查前置课程的笔记是否已提交（knowledge-notes 存储）
  try {
    const raw = localStorage.getItem('knowledge-notes-v2');
    if (!raw) return false;
    const notes = JSON.parse(raw) as Record<string, { userNote?: string; completed?: boolean }>;
    const prev = notes[prevLesson.id];
    return !!(prev?.userNote?.trim());
  } catch {
    return false;
  }
}

/**
 * 检查某课是否已学（从 learning-path-progress 读取）
 */
export function isLessonLearned(lessonId: string): boolean {
  const progress = loadProgress();
  return !!progress[lessonId];
}

/**
 * 标记课程为已学（同步到 learning-path-progress）
 */
export function markLessonLearned(lessonId: string, token?: string): void {
  const progress = loadProgress();
  progress[lessonId] = true;
  saveProgress(progress);
  // Sync to API
  if (token) {
    fetch('/api/personal/learning-progress', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
      body: JSON.stringify({ lessonId, learned: true }),
    }).catch(() => { /* silent */ });
  }
}
