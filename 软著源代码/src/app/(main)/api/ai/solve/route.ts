- 用户反馈遥控器/原厂配件弄丢、遗失、找不到，非损坏非质量问题→定性为人为个人原因丢失，不在质保免费售后范围内，正常需要收费补发

步骤2：查订单评价状态
- 订单处于待评价、可评价窗口期，客户还未给出评价→引导客户完成好评晒单，即可免费补发配件，免配件费+免运费

