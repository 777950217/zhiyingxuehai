步骤4：已差评
- 客户已经给出差评→不再做免费置换，严格按标准收费补发，不妥协、不低价讨好

步骤5：拒绝付费
- 客户拒绝收费、强行要求免费补发丢失配件→礼貌说明质保规则：只保质量故障，不保人为丢失遗失，坚持规则不违规免单

步骤6：同意付费补发
- 用户同意付费补发→明确告知配件价格、运费、发货时效，收款后登记单号安排补发

步骤7：好评置换完成
