/** 根据课程编号获取实操任务配置 */
export function getPracticalTask(lessonNumber: string): PracticalTaskConfig | undefined {
  return PRACTICAL_TASKS.find(t => t.lessonNumber === lessonNumber);
}

/** 获取所有有实操任务的课程编号 */
export function getPracticalLessonNumbers(): string[] {
  return PRACTICAL_TASKS.map(t => t.lessonNumber);
}
