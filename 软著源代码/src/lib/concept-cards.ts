/** 版本类型 */
export type ConceptCardTier = 'personal' | 'professional' | 'flagship';

/** 根据版本和 lessonKey 查找概念卡 */
export function getConceptCard(lessonKey: string, tier: ConceptCardTier = 'personal'): ConceptCardData | undefined {
  const cards = tier === 'flagship'
    ? FLAGSHIP_CONCEPT_CARDS
    : tier === 'professional'
      ? PROFESSIONAL_CONCEPT_CARDS
      : PERSONAL_CONCEPT_CARDS;
  return cards.find(c => c.lessonKey === lessonKey);
}
